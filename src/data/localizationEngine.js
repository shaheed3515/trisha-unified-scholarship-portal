export function getLocalizedStudent(student, lang = 'en') {
  if (!student) return student;
  const l = lang in LOCALIZED_STUDENTS.student_priya ? lang : 'en';
  const meta = LOCALIZED_STUDENTS[student.id]?.[l] || {};
  
  const localizedApps = (student.applications || []).map(app => {
    const statusText = LOCALIZED_STATUS_MAP[app.status]?.[l] || app.statusText;
    const localizedStages = (app.stages || []).map(st => ({
      ...st,
      title: LOCALIZED_STAGES_MAP[st.id]?.[l] || st.title
    }));
    return {
      ...app,
      statusText,
      stages: localizedStages
    };
  });

  return {
    ...student,
    name: meta.name || student.name,
    relation: meta.relation || student.relation,
    educationLevel: meta.educationLevel || student.educationLevel,
    institution: meta.institution || student.institution,
    academicProgram: meta.academicProgram || student.academicProgram,
    yearOfStudy: meta.yearOfStudy || student.yearOfStudy,
    applications: localizedApps
  };
}

export function getLocalizedHousehold(household, lang = 'en') {
  if (!household) return household;
  const l = lang in LOCALIZED_STUDENTS.student_priya ? lang : 'en';
  const meta = {
    headOfHousehold: LOCALIZED_HOUSEHOLD_META.headOfHousehold[l] || household.headOfHousehold,
    village: LOCALIZED_HOUSEHOLD_META.village[l] || household.village,
    district: LOCALIZED_HOUSEHOLD_META.district[l] || household.district,
    state: LOCALIZED_HOUSEHOLD_META.state[l] || household.state,
    tribalGroup: LOCALIZED_HOUSEHOLD_META.tribalGroup[l] || household.tribalGroup
  };

  const localizedMembers = (household.members || []).map(m => getLocalizedStudent(m, l));

  return {
    ...household,
    ...meta,
    members: localizedMembers
  };
}

